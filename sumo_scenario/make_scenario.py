#!/usr/bin/env python3
"""Generate the SUMO scenarios and their edge-server layouts.

    python sumo_scenario/make_scenario.py            # builds both scenarios

small : 4x4 grid, 200 m blocks (600 m x 600 m), 500 trips, 4 edge servers
city  : 8x8 grid, 250 m blocks (1750 m x 1750 m), 2000 trips, 16 edge servers

For each scenario it writes, into sumo_scenario/<name>/:
    grid.net.xml      road network        (SUMO netgenerate)
    routes.rou.xml    vehicle routes      (SUMO randomTrips.py + duarouter)
    servers.csv       edge servers: id, name, x, y, cpu_capacity, colour  (read by iov_sim)
    servers.add.xml   the same servers drawn as coloured circles in sumo-gui
    grid.sumocfg      SUMO configuration
Everything uses fixed seeds, so the files are reproducible.
"""
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# Colour per capacity class (validated colour-blind-safe palette).
CLASS_COLOR = {2.0: (42, 120, 214), 3.0: (235, 104, 52), 4.0: (27, 175, 122), 6.0: (98, 80, 214)}

SCENARIOS = {
    "small": dict(grid=4, block=200.0, trips_end=500, period=1.0, seed=7,
                  servers=[(100, 100, 2.0), (500, 100, 3.0), (100, 500, 3.0), (500, 500, 6.0)]),
    "city": dict(grid=8, block=250.0, trips_end=600, period=0.3, seed=11, servers=None),
}


def city_servers():
    """16 servers on a 4x4 lattice; each row holds one server of every class,
    rotated per row so that fast and slow servers are spread over the map."""
    size = 7 * 250.0
    step = size / 4
    classes = [2.0, 3.0, 4.0, 6.0]
    out = []
    for r in range(4):
        for c in range(4):
            out.append((step * (c + 0.5), step * (r + 0.5), classes[(c + r) % 4]))
    return out


def tool(name):
    try:
        import sumo
        base = os.path.dirname(sumo.__file__)
    except ImportError:
        base = os.environ.get("SUMO_HOME")
    if not base:
        sys.exit("SUMO not found: python -m pip install eclipse-sumo")
    return os.path.join(base, "tools", name), os.path.join(base, "bin")


def build(name, cfg):
    out = os.path.join(HERE, name)
    os.makedirs(out, exist_ok=True)
    random_trips, bindir = tool("randomTrips.py")
    exe = ".exe" if os.name == "nt" else ""
    net = os.path.join(out, "grid.net.xml")
    subprocess.run([os.path.join(bindir, "netgenerate" + exe), "--grid", "--grid.number", str(cfg["grid"]),
                    "--grid.length", str(cfg["block"]), "--default.lanenumber", "1",
                    "--tls.guess", "true", "-o", net], check=True, stdout=subprocess.DEVNULL)
    subprocess.run([sys.executable, random_trips, "-n", net, "-o", os.path.join(out, "trips.trips.xml"),
                    "-r", os.path.join(out, "routes.rou.xml"), "--prefix", "veh", "-b", "0",
                    "-e", str(cfg["trips_end"]), "-p", str(cfg["period"]), "--fringe-factor", "5",
                    "--seed", str(cfg["seed"]), "--validate"], check=True, stdout=subprocess.DEVNULL)
    for f in os.listdir(out):  # drop duarouter side files
        if f.endswith((".alt.xml", ".rou.alt.xml")):
            os.remove(os.path.join(out, f))

    servers = cfg["servers"] or city_servers()
    with open(os.path.join(out, "servers.csv"), "w") as f:
        f.write("server_id,name,x,y,cpu_capacity,r,g,b\n")
        for i, (x, y, cap) in enumerate(servers):
            r, g, b = CLASS_COLOR[cap]
            f.write(f"{i},S{i},{x:.2f},{y:.2f},{cap:g},{r},{g},{b}\n")
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- Edge servers for sumo-gui (generated by make_scenario.py; purely visual). -->",
             "<additional>"]
    for i, (x, y, cap) in enumerate(servers):
        r, g, b = CLASS_COLOR[cap]
        pts = " ".join(f"{x + 28 * math.cos(2 * math.pi * k / 24):.1f},{y + 28 * math.sin(2 * math.pi * k / 24):.1f}"
                       for k in range(24))
        lines.append(f'    <poly id="S{i}_area" type="edge_server" color="{r},{g},{b},90" fill="1" layer="-1" shape="{pts}"/>')
        lines.append(f'    <poi id="S{i} ({cap:g} Mcycles/ms)" type="edge_server" color="{r},{g},{b}" layer="10" '
                     f'x="{x:.1f}" y="{y:.1f}" width="14" height="14"/>')
    lines.append("</additional>")
    with open(os.path.join(out, "servers.add.xml"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(out, "grid.sumocfg"), "w") as f:
        f.write(f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Scenario '{name}': {cfg['grid']}x{cfg['grid']} grid, {cfg['block']:g} m blocks. The experiment driver
     controls the clock over TraCI, so no end time is set here. -->
<configuration>
    <input>
        <net-file value="grid.net.xml"/>
        <route-files value="routes.rou.xml"/>
        <additional-files value="servers.add.xml"/>
    </input>
    <time>
        <step-length value="0.1"/>
    </time>
    <processing>
        <time-to-teleport value="300"/>
    </processing>
    <report>
        <no-step-log value="true"/>
        <no-warnings value="true"/>
    </report>
    <random_number>
        <seed value="42"/>
    </random_number>
</configuration>
""")
    n_trips = open(os.path.join(out, "routes.rou.xml")).read().count("<vehicle ")
    print(f"{name}: {cfg['grid']}x{cfg['grid']} grid, {len(servers)} servers, {n_trips} routed trips -> {out}")


def main():
    names = sys.argv[1:] or list(SCENARIOS)
    for n in names:
        build(n, SCENARIOS[n])


if __name__ == "__main__":
    main()
